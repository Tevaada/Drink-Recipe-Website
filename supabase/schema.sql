-- Allows an authenticated member to permanently delete their own account.
create or replace function public.delete_account()
returns void
language sql
security definer
set search_path = ''
as $$
    delete from auth.users
    where id = auth.uid();
$$;

revoke all
    on function public.delete_account()
    from public;

grant execute
    on function public.delete_account()
    to authenticated;
